const fs = require('fs');
const path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../public/index.html'), 'utf8');
const start = html.indexOf('<div id="settingsModal"');
const end = html.indexOf('<!-- Modal 4B: API Providers & Usage -->', start);
if (start < 0 || end < 0) throw new Error('Settings modal boundaries not found');
const modal = html.slice(start, end);
const contentStart = modal.indexOf('<div class="bg-white rounded-2xl border border-slate-200 max-w-lg');
const save = modal.indexOf('id="saveSettingsModalBtn"');
const contentEnd = modal.lastIndexOf('</div>');
if (contentStart < 0 || save < 0 || contentEnd < save) throw new Error('Save button is not inside settings modal content');
if (!/max-h-\[90vh\].*overflow-y-auto/.test(modal.slice(contentStart, save))) throw new Error('Scrollable modal container missing');
const prefix = modal.slice(0, save);
const opens = (prefix.match(/<div\b/g) || []).length;
const closes = (prefix.match(/<\/div>/g) || []).length;
if (opens <= closes) throw new Error('Modal content closed before save button; possible stray closing div');
console.log('Settings modal structure regression passed');
